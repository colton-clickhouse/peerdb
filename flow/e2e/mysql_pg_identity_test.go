package e2e

import (
	"fmt"
	"time"

	"github.com/stretchr/testify/require"
)

// An AUTO_INCREMENT column must arrive as an identity, so that after cutover, with its sequence set to the
// replicated maximum (the cutover step), an application insert without an id gets the next one, as it would on
// MySQL. BIGINT UNSIGNED (SERIAL, Laravel's default id) stays bigint, which can be an identity.
func (s MySQLPGSuite) Test_Auto_Increment_As_Identity() {
	t := s.t
	srcTable := "auto_increment_identity"
	srcFull := AttachSchema(s, srcTable)
	dstFull := s.DestinationTable(srcTable)
	require.NoError(t, s.source.Exec(t.Context(), fmt.Sprintf(
		`CREATE TABLE %s (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, v VARCHAR(10))`, srcFull)))
	require.NoError(t, s.source.Exec(t.Context(), fmt.Sprintf(`INSERT INTO %s (v) VALUES ('a'), ('b'), ('c')`, srcFull)))

	connectionGen := FlowConnectionGenerationConfig{
		FlowJobName:   AddSuffix(s, srcTable),
		TableMappings: TableMappings(s, srcTable, srcTable),
		Destination:   s.Peer().Name,
	}
	flowConnConfig := connectionGen.GenerateFlowConnectionConfigs(s)
	flowConnConfig.DoInitialSnapshot = true
	tc := NewTemporalClient(t)
	env := ExecutePeerflow(t, tc, flowConnConfig)
	SetupCDCFlowStatusQuery(t, env, flowConnConfig)
	EnvWaitFor(t, env, 3*time.Minute, "initial load", func() bool {
		return s.destInt(fmt.Sprintf(`SELECT count(*) FROM %s`, dstFull)) == 3
	})
	EnvNoError(t, env, s.source.Exec(t.Context(), fmt.Sprintf(`INSERT INTO %s (v) VALUES ('d'), ('e')`, srcFull)))
	EnvWaitFor(t, env, 2*time.Minute, "cdc inserts", func() bool {
		return s.destInt(fmt.Sprintf(`SELECT count(*) FROM %s`, dstFull)) == 5
	})

	var identity string
	EnvNoError(t, env, s.dest.Conn().QueryRow(t.Context(),
		`SELECT attidentity::text FROM pg_attribute WHERE attrelid = $1::regclass AND attname = 'id'`, dstFull).Scan(&identity))
	env.Cancel(t.Context())
	RequireEnvCanceled(t, env)
	require.Equal(t, "d", identity, "id should be GENERATED BY DEFAULT AS IDENTITY")

	// cutover: the sequence to the replicated maximum, then the application's first insert
	_, err := s.dest.Conn().Exec(t.Context(),
		fmt.Sprintf(`SELECT setval(pg_get_serial_sequence($1, 'id'), max(id)) FROM %s`, dstFull), dstFull)
	require.NoError(t, err)
	var id int64
	require.NoError(t, s.dest.Conn().QueryRow(t.Context(),
		fmt.Sprintf(`INSERT INTO %s (v) VALUES ('app') RETURNING id`, dstFull)).Scan(&id))
	require.Equal(t, int64(6), id)
}
